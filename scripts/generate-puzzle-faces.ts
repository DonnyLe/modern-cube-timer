// Regenerates src/core/puzzleFaces.ts from cubing.js's solved SVG nets.
// Run with `bun scripts/generate-puzzle-faces.ts` after upgrading cubing.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { puzzles as loaders } from 'cubing/puzzles';
import { puzzleEvents, puzzles } from '../src/core/puzzles';

const output = fileURLToPath(new URL('../src/core/puzzleFaces.ts', import.meta.url));
const browser = await chromium.launch();
const page = await browser.newPage();
const faces: Record<string, { viewBox: string; stickers?: string[] }> = {};

for (const event of puzzleEvents) {
  const svg = await loaders[puzzles[event].puzzleId].svg();

  faces[event] = await page.evaluate(
    ({ svg, event }) => {
      const round = (value: number) => Math.round(value * 100) / 100;
      const parsed = new DOMParser().parseFromString(svg, 'image/svg+xml');
      const root = document.importNode(parsed.documentElement, true) as unknown as SVGSVGElement;

      document.body.replaceChildren(root);

      // The clock net shows front and back side by side; keep the front.
      if (event === 'clock') {
        const box = root.viewBox.baseVal;

        return { viewBox: [box.x, box.y, box.width / 2, box.height].map(round).join(' ') };
      }

      const stickers = Array.from(root.querySelectorAll<SVGGraphicsElement>('[id]')).filter(
        (element) => /-l\d+-o\d+$/.test(element.id),
      );
      // Square-1 shows its white top; other puzzles show their green front face.
      const color =
        event === 'sq1'
          ? 'white'
          : ['limegreen', '#44ee00', '#008800'].find((fill) =>
              stickers.some((element) => element.style.fill === fill),
            ) || stickers[0]?.style.fill;
      const face = stickers.filter((element) => element.style.fill === color);

      if (!face.length) throw new Error(`No face stickers found for ${event}`);
      const inverse = root.getScreenCTM()!.inverse();
      const points = face.flatMap((element) => {
        const box = element.getBBox();
        const matrix = inverse.multiply(element.getScreenCTM()!);

        return [
          [box.x, box.y],
          [box.x + box.width, box.y],
          [box.x, box.y + box.height],
          [box.x + box.width, box.y + box.height],
        ].map(([x, y]) => new DOMPoint(x, y).matrixTransform(matrix));
      });
      const x = Math.min(...points.map((point) => point.x));
      const y = Math.min(...points.map((point) => point.y));
      const width = Math.max(...points.map((point) => point.x)) - x;
      const height = Math.max(...points.map((point) => point.y)) - y;
      const padding = Math.max(width, height) * 0.04;

      return {
        viewBox: [x - padding, y - padding, width + 2 * padding, height + 2 * padding]
          .map(round)
          .join(' '),
        stickers: face.map((element) => element.id),
      };
    },
    { svg, event },
  );
}

await browser.close();
await writeFile(
  output,
  `// Generated by scripts/generate-puzzle-faces.ts. Do not edit by hand.
import type { PuzzleEvent } from './puzzles';

// The crop and visible stickers for each puzzle's single-face preview.
export const puzzleFaces: Record<PuzzleEvent, { viewBox: string; stickers?: readonly string[] }> =
  ${JSON.stringify(faces, null, 2)};
`,
);
